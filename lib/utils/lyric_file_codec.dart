  static String? decode(List<int> bytes) {
    const localQrcHeader = [
      0x98,
      0x25,
      0xb0,
      0xac,
      0xe3,
      0x02,
      0x83,
      0x68,
      0xe8,
      0xfc,
      0x6c,
    ];
    if (bytes.length >= localQrcHeader.length &&
        List.generate(
          localQrcHeader.length,
          (i) => bytes[i] == localQrcHeader[i],
        ).every((b) => b)) {
      final decrypted = List<int>.generate(
        bytes.length,
        (i) => bytes[i] ^ _qmcKey[(i > 0x7fff ? i % 0x7fff : i) & 0x7f],
      );
      return decryptQrc(decrypted.sublist(11));
    }
    if (bytes.length >= 4 &&
        ascii.decode(bytes.take(4).toList(), allowInvalid: true) == 'krc1') {
      final payload = Uint8List.fromList(bytes.skip(4).toList());
      for (var i = 0; i < payload.length; i++) {
        payload[i] ^= krcKey[i % krcKey.length];
      }
      return _inflate(payload);
    }
    final raw = utf8.decode(bytes, allowMalformed: true).trim();
    if (raw.length >= 16 &&
        raw.length % 16 == 0 &&
        RegExp(r'^[0-9a-fA-F]+$').hasMatch(raw)) {
      final payload = Uint8List.fromList([
        for (var i = 0; i < raw.length; i += 2)
          int.parse(raw.substring(i, i + 2), radix: 16),
      ]);
      return decryptQrc(payload);
    }
    return null;
  }

