  static String _inflate(List<int> bytes) {
    final decoded = ZLibDecoder().decodeBytes(bytes);
    if (decoded.length > 100 * 1024 * 1024) {
      throw const FormatException('歌词文件解压后过大');
    }
    return utf8.decode(decoded).replaceAll('\uFEFF', '');
  }

  static String decryptQrc(List<int> input) {
    if (input.isEmpty || input.length % 8 != 0) {
      throw const FormatException('QRC 数据长度无效');
    }
    final keys = [
      _schedule(ascii.encode('!@#)(NHL')).reversed.toList(),
      _schedule(ascii.encode('123ZXC!@')),
      _schedule(ascii.encode(r'!@#)(*$%')).reversed.toList(),
    ];
    final output = Uint8List(input.length);
    for (var block = 0; block < input.length; block += 8) {
      var value = BigInt.zero;
      for (var i = 0; i < 8; i++) {
        value = (value << 8) | BigInt.from(input[block + i]);
      }
      for (final schedule in keys) {
        value = _block(value, schedule);
      }
      for (var i = 0; i < 8; i++) {
        output[block + i] = ((value >> (56 - i * 8)) & BigInt.from(255))
            .toInt();
      }
    }
    return _inflate(output);
  }

  static BigInt _permute(BigInt input, List<int> positions, int width) {
    if (width == 32) {
      // Round permutations read 32 bits and produce at most 48. Keep the hot
      // loop in exact integer arithmetic, including JS's 53-bit number range.
      final value = input.toInt();
      var result = 0;
      for (final position in positions) {
        result = result * 2 + ((value >> (32 - position)) & 1);
      }
      return BigInt.from(result);
    }
    var result = BigInt.zero;
    for (final position in positions) {
      result = (result << 1) | ((input >> (width - position)) & BigInt.one);
    }
    return result;
  }

  static List<int> _schedule(List<int> bytes) {
    int select(List<int> positions) {
      var out = 0;
      for (final bit in positions) {
        final index = (bit ~/ 32) * 4 + 3 - ((bit % 32) ~/ 8);
        out = (out << 1) | ((bytes[index] >> (7 - bit % 8)) & 1);
      }
      return out;
    }

    var c = select(_pc1c), d = select(_pc1d);
    final out = <int>[];
    for (final shift in _shifts) {
      c = ((c << shift) | (c >> (28 - shift))) & 0xfffffff;
      d = ((d << shift) | (d >> (28 - shift))) & 0xfffffff;
      var key = 0;
      for (final position in _pc2) {
        final bit = position < 28
            ? (c >> (27 - position)) & 1
            : position == 55
            ? 0
            : (d >> (27 - (position - 27))) & 1;
        key = (key << 1) | bit;
      }
      out.add(key);
    }
    return out;
  }

  static BigInt _block(BigInt value, List<int> keys) {
    final permuted = _permute(value, _ip, 64);
    var left = (permuted >> 32).toInt();
    var right = (permuted & BigInt.from(0xffffffff)).toInt();
    for (final key in keys) {
      final expanded =
          _permute(BigInt.from(right), _expansion, 32).toInt() ^ key;
      var substitution = 0;
      for (var box = 0; box < 8; box++) {
        final six = (expanded >> (42 - box * 6)) & 63;
        final index = (six & 32) | ((six & 31) >> 1) | ((six & 1) << 4);
        substitution = (substitution << 4) | _sboxes[box][index];
      }
      final next =
          (left ^ _permute(BigInt.from(substitution), _p, 32).toInt()) &
          0xffffffff;
      left = right;
      right = next;
    }
    return _permute((BigInt.from(right) << 32) | BigInt.from(left), _fp, 64);
  }

