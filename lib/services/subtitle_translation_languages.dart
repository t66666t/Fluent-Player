String normalizeSubtitleLanguage(String code) {
  final raw = code.trim().toLowerCase();
  if (raw.isEmpty || raw == 'auto' || raw == 'auto-detect') return 'auto';
  final alias = switch (raw) {
    'zh' || 'zh-hans' || 'zh-cn' => 'zh-CN',
    'zh-hant' || 'zh-tw' => 'zh-TW',
    'tl' => 'fil',
    'mn' => 'mn-Cyrl',
    'pt-br' => 'pt',
    'no' => 'nb',
    _ => code.trim(),
  };
  return subtitleTranslationLanguages
          .where((item) => item.code.toLowerCase() == alias.toLowerCase())
          .firstOrNull
          ?.code ??
      alias;
}

String subtitleLanguageLabel(String code) => code == 'auto'
    ? '自动检测'
    : subtitleTranslationLanguages
              .where((item) => item.code == normalizeSubtitleLanguage(code))
              .firstOrNull
              ?.label ??
          code;

List<SubtitleTranslationLanguage> subtitleLanguagesForModel(List<String> tags) {
  if (tags.isEmpty) return subtitlePopularLanguages;
  final codes = {for (final tag in tags) normalizeSubtitleLanguage(tag)};
  if (tags.contains('zh')) codes.addAll(['zh-CN', 'zh-TW']);
  final known = subtitleTranslationLanguages
      .where((item) => codes.contains(item.code))
      .toList();
  return known.isEmpty ? subtitlePopularLanguages : known;
}
